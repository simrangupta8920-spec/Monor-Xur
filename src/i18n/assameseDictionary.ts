  m = trimmed.match(/^Tracking\s+(.+?)'s cognitive engagement, response speed, and adaptive difficulty over time\.$/i);
  if (m) return `সময়ৰ লগে লগে ${m[1]}ৰ বৌদ্ধিক অংশগ্ৰহণ, সঁহাৰিৰ গতি আৰু অভিযোজিত কঠিনতাৰ নিৰীক্ষণ।`;

